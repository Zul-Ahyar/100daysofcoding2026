public class Day6 {

    public static void main(String[] args) {

        // char digunakan untuk menyimpan satu karakter. 
        // Kemudian karakter ditulis menggunakan tanda petik satu (' ').
        char inisialSaya ='Z';

        // boolean digunakan untuk menyimpan nilai benar atau salah.
        // Nilainya itu hanya bisa true atau false.
        boolean benar = true;  
        
        // printf digunakan untuk menampilkan output dengan format tertentu.
        // %c digunakan untuk menampilkan nilai char.
        // %b digunakan untuk menampilkan nilai boolean. 
        // %n digunakan untuk pindah ke baris berikutnya.
        System.out.printf("Inisial saya adalah: %c%n", inisialSaya);
        System.out.printf("Apakah benar inisial adalah Z: %b%n", benar);
    }
}
