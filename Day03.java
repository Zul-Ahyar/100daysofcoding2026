public class Day3 {

    public static void main(String[] args) {

        // \n digunakan untuk membuat baris baru setelah teks ditampilkan.
        System.out.print("Nama saya: Zul\n");

        // \t digunakan untuk memberikan jarak seperti tab.
        System.out.println("Saya kelahiran:\t2007");

        // \" digunakan untuk menampilkan tanda petik dua sebagai bagian dari teks.
        System.out.println("Asal saya:\"Pasangkayu\"");

        // \\ digunakan untuk menampilkan karakter backslash (\).
        System.out.println("Saya mengambil prodi:\\Informatika");

        // \b digunakan untuk menggeser posisi kursor satu karakter ke belakang.
        System.out.println("E\bEZ");

        // \' digunakan untuk menampilkan tanda petik satu.
        System.out.println("Saya suka karakter \'Z\'");
    }
}
