public class Day8 {

    public static void main(String[] args) {

        // Membuat variabel umur dengan tipe data int untuk menyimpan bilangan bulat.
        int umur = 19;

        // println digunakan untuk menampilkan output lalu pindah ke baris berikutnya.
        System.out.println("Umur sebelum update: " + umur);

        // Mengganti nilai variabel umur dari 19 menjadi 20.
        umur = 20;

        // println digunakan untuk menampilkan output lalu pindah ke baris berikutnya.
        System.out.println("Umur sesudah update: " + umur);
    }
}
