public class Day3 {

    public static void main(String[] args) {

        // Membuat variabel nama dengan tipe data String.
        String nama = "Zul";

        // Membuat variabel tahunLahir dengan tipe data int untuk menyimpan bilangan bulat.
        int tahunLahir = 2007;

        // Membuat variabel asal dengan tipe data String.
        String asal = "Pasangkayu";

        // Membuat variabel prodi dengan tipe data String.
        String prodi = "Informatika";

        // \n digunakan untuk membuat baris baru setelah teks ditampilkan.
        System.out.print("Nama saya: " + nama + "\n");

        // \t digunakan untuk memberikan jarak seperti tab.
        System.out.println("Saya kelahiran:\t2007");

        // \" digunakan untuk menampilkan tanda petik dua sebagai bagian dari teks.
        System.out.println("Asal saya:\"Pasangkayu\"");

        // \\ digunakan untuk menampilkan karakter backslash (\).
        System.out.println("Saya mengambil prodi:\\informatika");
    }
}
