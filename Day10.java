public class Day10 {

    public static void main(String[] args) {
        // Menampilkan batas nilai minimum dan maksimum dari tipe data integer di Java
        System.out.println("Nilai minimum byte  : " + Byte.MIN_VALUE);
        System.out.println("Nilai maksimum byte  : " + Byte.MAX_VALUE);

        System.out.println("Nilai minimum short : " + Short.MIN_VALUE);
        System.out.println("Nilai maksimum short : " + Short.MAX_VALUE);

        System.out.println("Nilai minimum int   : " + Integer.MIN_VALUE);
        System.out.println("Nilai maksimum int   : " + Integer.MAX_VALUE);

        System.out.println("Nilai minimum long  : " + Long.MIN_VALUE);
        System.out.println("Nilai maksimum long  : " + Long.MAX_VALUE);
    }
}
